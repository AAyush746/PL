async def seed_training_modules(db: AsyncSession) -> None:
    """Idempotent seed of the global lesson library. Only runs when no global
    module exists yet, so tenant edits and future versions are preserved."""
    existing = (await db.execute(
        select(TrainingModule).where(TrainingModule.org_id.is_(None)).limit(1)
    )).scalars().first()
    if existing is None:
        for index, spec in enumerate(SEED_MODULES):
            module = TrainingModule(
                org_id=None,
                title=spec["title"],
                title_ne=spec["title_ne"],
                description=spec["description"],
                description_ne=spec["description_ne"],
                failure_type=spec["failure_type"],
                video_url_en=_media_url(spec["failure_type"], "en"),
                video_url_ne=_media_url(spec["failure_type"], "ne"),
                audio_url_en=None,
                audio_url_ne=None,
                duration_seconds=lesson_duration_seconds(spec["failure_type"], "en"),
                pass_score=80,
                key_points_en=spec["key_points_en"],
                key_points_ne=spec["key_points_ne"],
                is_active=True,
                version=1,
            )
            db.add(module)
            await db.flush()
            for q in spec["questions"]:
                db.add(TrainingQuestion(
                    module_id=module.id,
                    prompt=q["prompt"],
                    prompt_ne=q["prompt_ne"],
                    options=q["options"],
                    correct_index=q["correct_index"],
                    checkpoint_after_seconds=q["checkpoint_after_seconds"],
                    explanation=q["explanation"],
                    explanation_ne=q["explanation_ne"],
                ))
    await _refresh_seeded_videos(db)
    await db.commit()


async def _refresh_seeded_videos(db: AsyncSession) -> None:
    """Swap any global module still on a legacy/off-topic media URL onto its
    topic-specific training video, and enforce the minimum lesson length."""
    modules = (
        await db.execute(select(TrainingModule).where(TrainingModule.org_id.is_(None)))
    ).scalars().all()
    changed = False
    for module in modules:
        if module.video_url_en in LEGACY_VIDEO_URLS or not module.video_url_en:
            module.video_url_en = _media_url(module.failure_type or "phishing-basics", "en")
            changed = True
        elif not str(module.video_url_en).startswith(MEDIA_BASE):
            module.video_url_en = _media_url(module.failure_type or "phishing-basics", "en")
            changed = True
        if module.video_url_ne in LEGACY_VIDEO_URLS or not module.video_url_ne:
            module.video_url_ne = _media_url(module.failure_type or "phishing-basics", "ne")
            changed = True
        elif not str(module.video_url_ne).startswith(MEDIA_BASE):
            module.video_url_ne = _media_url(module.failure_type or "phishing-basics", "ne")
            changed = True
        expected = lesson_duration_seconds(module.failure_type or "phishing-basics", "en")
        if abs((module.duration_seconds or 0) - expected) > 2:
            module.duration_seconds = expected
            changed = True
    if changed:
        await db.flush()
