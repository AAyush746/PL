# Minimum lesson length. The generated lesson videos run 2.3-3.1 minutes; the
# client reports the real media duration and verified watch time must cover
# 95% of it, so this floor only guards against future regressions.
MIN_LESSON_SECONDS = 130  # ~2 minutes 10 seconds

_DURATIONS_CACHE: dict | None = None


def lesson_duration_seconds(failure_type: str, lang: str) -> float:
    """True media length from durations.json (written by the video generator).
    Falls back to MIN_LESSON_SECONDS when the manifest is unavailable."""
    global _DURATIONS_CACHE
    if _DURATIONS_CACHE is None:
        manifest = Path(__file__).resolve().parent.parent / "media" / "training" / "durations.json"
        try:
            _DURATIONS_CACHE = json.loads(manifest.read_text())
        except (OSError, ValueError):
            _DURATIONS_CACHE = {}
    return float(
        (_DURATIONS_CACHE.get(failure_type) or {}).get(lang, MIN_LESSON_SECONDS)
    )

# Map a campaign's template category to the failure type it is teaching about.
CATEGORY_TO_FAILURE = {key.lower(): value for key, value in {
    "Finance": "credential-phishing",
    "Internal IT": "credential-phishing",
    "Collaboration": "malware-link",
    "HR": "urgency-bait",
    "Delivery": "urgency-bait",
}.items()}
FALLBACK_FAILURE = "phishing-basics"


# ── Verified-time helpers ───────────────────────────────────────────────────

def _as_utc(dt) -> datetime:
    """SQLite returns offset-naive datetimes; normalize to aware UTC."""
    if dt is None:
        return datetime.now(timezone.utc)
    if dt.tzinfo is None:
        return dt.replace(tzinfo=timezone.utc)
    return dt.astimezone(timezone.utc)


def _merge_segments(segments: list, start: float, end: float) -> list:
    """Add [start, end] to a list of verified [start, end] segments and return
    the normalized (merged) union. Segments that don't overlap the new window
    (entirely before or after it) are kept as-is; the rest are unioned."""
    if start is None or end is None or end <= start or start < 0:
        return segments or []
    merged = [seg for seg in (segments or []) if seg[1] <= start or seg[0] >= end]
    merged.append([start, end])
    merged.sort(key=lambda pair: pair[0])
    out = []
    for lo, hi in merged:
        if out and lo <= out[-1][1]:
            out[-1][1] = max(out[-1][1], hi)
        else:
            out.append([lo, hi])
    return out


def _union_length(segments: list) -> float:
    return sum(hi - lo for lo, hi in segments)


def _append_flag(attempt: TrainingAttempt, flag: str) -> None:
    flags = list(attempt.invalid_flags or [])
    if flag not in flags:
        flags.append(flag)
        attempt.invalid_flags = flags


# ── Shared helpers ──────────────────────────────────────────────────────────

async def _resolve_result(token: str, db: AsyncSession) -> tuple[CampaignResult | None, Campaign | None]:
    try:
        token_uuid = uuid.UUID(str(token))
    except (ValueError, AttributeError, TypeError):
        return None, None
    result = await db.scalar(select(CampaignResult).where(CampaignResult.tracking_token == token_uuid))
    if result is None:
        return None, None
    campaign = await db.scalar(select(Campaign).where(Campaign.id == result.campaign_id))
    return result, campaign


async def _pick_module(db: AsyncSession, org_id, campaign: Campaign | None) -> TrainingModule | None:
    failure = FALLBACK_FAILURE
    if campaign is not None:
        from .models import PhishingTemplate  # local import to avoid circulars

        template = await db.get(PhishingTemplate, campaign.template_id)
        failure = CATEGORY_TO_FAILURE.get((template.category or "").strip().lower(), FALLBACK_FAILURE)

    stmt = select(TrainingModule).where(
        TrainingModule.failure_type == failure,
        TrainingModule.is_active == True,  # noqa: E712
        (TrainingModule.org_id.is_(None)) | (TrainingModule.org_id == org_id),
    ).order_by(TrainingModule.org_id.is_(None), TrainingModule.version.desc())
    module = (await db.execute(stmt)).scalars().first()
    if module is None and failure != FALLBACK_FAILURE:
        stmt = select(TrainingModule).where(
            TrainingModule.failure_type == FALLBACK_FAILURE,
            TrainingModule.is_active == True,  # noqa: E712
            (TrainingModule.org_id.is_(None)) | (TrainingModule.org_id == org_id),
        ).order_by(TrainingModule.org_id.is_(None), TrainingModule.version.desc())
        module = (await db.execute(stmt)).scalars().first()
    if module is None:
        module = (await db.execute(
            select(TrainingModule).where(
                TrainingModule.is_active == True,  # noqa: E712
                (TrainingModule.org_id.is_(None)) | (TrainingModule.org_id == org_id),
            ).order_by(TrainingModule.org_id.is_(None))
        )).scalars().first()
    return module


async def _load_questions(db: AsyncSession, module_id) -> list[TrainingQuestion]:
    return (await db.execute(
        select(TrainingQuestion).where(TrainingQuestion.module_id == module_id)
    )).scalars().all()


def _public_question(q: TrainingQuestion) -> dict:
    """Question payload with NO answer key — the server validates answers."""
    return {
        "id": q.id,
        "prompt": q.prompt,
        "prompt_ne": q.prompt_ne,
        "options": q.options,
        "checkpoint_after_seconds": q.checkpoint_after_seconds,
    }


def _session_ok(attempt: TrainingAttempt, session: str, now: datetime) -> bool:
    """Single-active-session check. Returns True if this session may write."""
    if not attempt.session_id or attempt.session_id == session:
        return True
    last = _as_utc(attempt.last_activity_at)
    if last is None or (now - last).total_seconds() >= SESSION_CLAIM_TTL_SECONDS:
        attempt.session_id = session  # stale session expired — claim the tab
        return True
    return False


def _coverage(attempt: TrainingAttempt, module: TrainingModule) -> tuple[float, float]:
    duration = attempt.video_duration or module.duration_seconds or 1
    verified = _union_length(attempt.watch_segments or [])
    coverage = min(100.0, round(verified / duration * 100, 1)) if duration else 0.0
    return verified, coverage


