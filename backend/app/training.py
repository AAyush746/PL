"""
Interactive, tamper-resistant remediation lessons (public endpoints).

Flow: an employee who clicked a simulated phish reaches the awareness-reveal
page, which links here. They pick a medium (watch / listen) and a language
(English / Nepali), then complete the lesson. Playback is verified server-side:

    browser reports playback  ->  backend validates  ->  backend decides

The backend never trusts ``currentTime == duration``. It maintains a UNION of
verified watch segments built from heartbeats, so seeking to the end counts as
nothing, tab-switches pause verified time, and only one playback session per
attempt can contribute time at a time. Completion additionally requires every
interactive checkpoint answered correctly and a quiz score >= pass_score.
"""

