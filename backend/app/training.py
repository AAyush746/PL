# Verified segments are only accepted when playback advances by no more than
# server-elapsed time + this allowance (seconds). Anything bigger is a seek.
SEEK_ALLOWANCE_SECONDS = 6.0
# A new browser window may only take over the active session after this many
# seconds of silence from the previous one.
SESSION_CLAIM_TTL_SECONDS = 60.0
COMPLETION_COVERAGE = 0.95  # >= 95% verified coverage required

